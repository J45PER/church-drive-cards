// Writes the colour files the apps and the dashboards read, from design/clive/cards.json (entity_colours), so there is one source:
//   companion/android/core/src/main/java/com/churchdrive/app/ui/CliveColours.kt   (phone, To-Do, Satellites, watch)
//   src/clive-colours.js                                                          (the Home Assistant cards)
// `node tools/gen-clive-colours.mjs --check` fails if they are out of date (CI), without writing.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const check = process.argv.includes('--check');
const ec = JSON.parse(readFileSync('design/clive/cards.json', 'utf8')).entity_colours;
const SLOTS = ec.slots; // colour, dark, accent, light, deep
const pascal = (k) => k.split('_').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const argb = (h) => '0xFF' + h.slice(1).toUpperCase();

const kt = [
  'package com.churchdrive.app.ui',
  '',
  'import androidx.compose.ui.graphics.Color',
  '',
  '// GENERATED by tools/gen-clive-colours.mjs from design/clive/cards.json (entity_colours). Do not edit by hand.',
  '',
  '/** Five colours for one kind of thing, as agreed on the Clive Entity Colours board. */',
  'class EntityColours(val colour: Color, val dark: Color, val accent: Color, val light: Color, val deep: Color)',
  '',
  '/** The colours of everything that is not an entity (backgrounds, text, lines, the app accent), light and dark. */',
  'class NeutralColours(val background: Color, val surface: Color, val surface2: Color, val line: Color, val text: Color, val soft: Color, val primary: Color, val onPrimary: Color)',
  '',
  'object CliveColours {',
];
for (const [k, v] of Object.entries(ec.types)) {
  const [colour, dark, accent, light, deep] = v.colours.map(argb);
  kt.push(`    /** ${v.name}. */`);
  kt.push(`    val ${pascal(k)} = EntityColours(Color(${colour}), Color(${dark}), Color(${accent}), Color(${light}), Color(${deep}))`);
}
const neutral = (n) => `NeutralColours(${['background', 'surface', 'surface2', 'line', 'text', 'soft', 'primary', 'on_primary'].map((s) => `Color(${argb(ec.neutral[n][s])})`).join(', ')})`;
kt.push('', `    val NeutralLight = ${neutral('light')}`, `    val NeutralDark = ${neutral('dark')}`, '', '    /** Every set by its key in cards.json. */', '    val byKey: Map<String, EntityColours> = mapOf(');
for (const k of Object.keys(ec.types)) kt.push(`        "${k}" to ${pascal(k)},`);
kt.push('    )', '', '    /** The key of each set (by identity), for LiveColours.resolve. */', '    val keyOf: Map<EntityColours, String> = byKey.entries.associate { (k, v) -> v to k }', '', '    /** Home Assistant colour names and the palette name each one means (cards.json, entity_colours.aliases). */', '    val aliases: Map<String, String> = mapOf(');
for (const [a, k] of Object.entries(ec.aliases.names)) kt.push(`        "${a}" to "${k}",`);
kt.push('    )', '}', '');

const js = [
  '// GENERATED by tools/gen-clive-colours.mjs from design/clive/cards.json (entity_colours). Do not edit by hand.',
  '// Five colours per kind of thing: [colour, dark, accent, light, deep]; the neutral colours are for everything that is not an entity.',
  `export const CLIVE_SLOTS = ${JSON.stringify(SLOTS)};`,
  'export const CLIVE = {',
  ...Object.entries(ec.types).map(([k, v]) => `  ${k}: ${JSON.stringify(v.colours.map((c) => c.toLowerCase()))},`),
  '};',
  `export const CLIVE_NEUTRAL = ${JSON.stringify(Object.fromEntries(Object.entries(ec.neutral).filter(([k]) => k !== 'note').map(([k, v]) => [k, Object.fromEntries(Object.entries(v).map(([a, b]) => [a, b.toLowerCase()]))])), null, 2)};`,
  '',
  `export const CLIVE_ALIASES = ${JSON.stringify(ec.aliases.names)};`,
  '',
  '/** One slot of a set, e.g. clive(\'lights\') is the colour, clive(\'lights\', \'dark\') its ground. */',
  'export function clive(key, slot = \'colour\') {',
  '  const set = CLIVE[key];',
  '  return set ? set[Math.max(0, CLIVE_SLOTS.indexOf(slot))] : undefined;',
  '}',
  '',
];

const groups = [...new Set(Object.values(ec.types).map((t) => t.group))];
const md = ['# Clive colour names', '', 'GENERATED by `tools/gen-clive-colours.mjs` from `design/clive/cards.json` (`entity_colours`). Do not edit by hand.', '',
  'One list of names for every colour the apps and the dashboards use. A dashboard card\'s `color` (and `alert_color`, `color_template`, `list_color`) is one of these names; the apps, the watch, the satellites and the Home Assistant cards all resolve it to the same five colours. Use a name, never a hex code, so a change to the palette changes everything.', '',
  'Each name has five colours: Colour (the thing\'s own), Dark (the ground), Accent (pulled towards Clive\'s purple), Light (highlight) and Deep (shadow).', ''];
for (const g of groups) {
  md.push(`## ${g}`, '', '| Name | Meaning | Colour | Dark | Accent | Light | Deep |', '|---|---|---|---|---|---|---|');
  for (const [k, t] of Object.entries(ec.types)) if (t.group === g) md.push(`| \`${k}\` | ${t.name} | ${t.colours.map((c) => `\`${c}\``).join(' | ')} |`);
  md.push('');
}
md.push('## Changing a colour', '', 'The palettes live in Home Assistant (the Church Drive integration keeps them; the colours below are what it ships). A change made there reaches the apps and the dashboards straight away, with no app update: `church_drive.set_palette` (key, name, five colours; administrators) or the `church_drive/colours/set` command. The apps and dashboards read `church_drive/colours` and follow the revision on `sensor.church_drive_colours`; the glow of the Clive cards on the phone, watch and satellite comes from the same sensor through `script.clive_show_card`. A colour a card names directly in code (a hex in a card\'s own style) is not a palette colour and only changes with a release.', '');
md.push('## Home Assistant colour names', '', ec.aliases.note, '', '| HA name | Means |', '|---|---|', ...Object.entries(ec.aliases.names).map(([a, k]) => `| \`${a}\` | \`${k}\` |`), '',
  '## Status', '', 'Status keeps its fixed meaning everywhere: `ok` is fine, `warn` needs attention, `bad` is wrong. A card for any entity turns to these when something is wrong, then goes back to its own name.', '');
const files = {
  'docs/CLIVE-COLOURS.md': md.join('\n'),
  'companion/android/core/src/main/java/com/churchdrive/app/ui/CliveColours.kt': kt.join('\n'),
  'src/clive-colours.js': js.join('\n'),
};
let stale = false;
for (const [path, text] of Object.entries(files)) {
  if (check) { if (!existsSync(path) || readFileSync(path, 'utf8') !== text) { console.error(`${path} is out of date: run node tools/gen-clive-colours.mjs`); stale = true; } }
  else { writeFileSync(path, text); console.log(path); }
}
if (check && stale) process.exit(1);
